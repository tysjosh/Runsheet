@pytest.mark.parametrize(
    ("product_code", "expected_api_gravity"),
    [
        ("DIESEL_2", 35.0),
        ("OFF_ROAD_DIESEL", 35.0),
        ("HEATING_OIL", 32.0),
        ("GASOLINE_REG", 60.0),
        ("GASOLINE_PREM", 60.0),
        ("KEROSENE", 43.0),
        ("PROPANE", 147.0),
        ("ETHANOL_E85", 48.0),
        ("DEF", 10.0),
    ],
)
def test_default_api_gravity_returns_expected_default_for_canonical_product(
    product_code: str,
    expected_api_gravity: float,
) -> None:
    """Every canonical US product code has a module-level default gravity.

    Validates: Requirement 2.8
    """
    result = _CALCULATOR.default_api_gravity(product_code)
    assert result == expected_api_gravity


def test_default_api_gravity_accepts_legacy_alias() -> None:
    """Legacy aliases (e.g. NG ``AGO`` ⇒ ``DIESEL_2``) canonicalize first.

    This pins the contract that callers can pass either canonical codes
    or legacy region-specific aliases without hitting the "unknown
    product" branch.

    Validates: Requirement 2.8
    """
    assert _CALCULATOR.default_api_gravity("AGO") == 35.0
    assert _CALCULATOR.default_api_gravity("PMS") == 60.0
    assert _CALCULATOR.default_api_gravity("LPG") == 147.0


@pytest.mark.parametrize(
    "product_code",
    [
        "NOT_A_REAL_PRODUCT",
        "",
        "RANDOM_STRING",
    ],
)
def test_default_api_gravity_raises_value_error_for_unknown_product(
    product_code: str,
) -> None:
    """Unknown product codes surface as ``ValueError``, not catalog errors.

    ``UnknownFuelProductError`` is a ``ValueError`` subclass, so catching
    ``ValueError`` is the documented pattern; we assert it here to lock
    in the contract that callers don't need to know about the catalog's
    internal error hierarchy.

    Validates: Requirement 2.8
    """
    with pytest.raises(ValueError):
        _CALCULATOR.default_api_gravity(product_code)
