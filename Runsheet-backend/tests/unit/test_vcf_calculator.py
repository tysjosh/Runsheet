# 6. compute_net_gallons rounding
# ---------------------------------------------------------------------------


def test_compute_net_gallons_rounds_to_one_decimal_place() -> None:
    """8000 gallons at 72 °F / 35 °API produces the rounded net baseline.

    The expected value was captured from the shipped polynomial (the
    equivalent of running ``compute_net_gallons(8000, 72, 35)`` once) so
    regressions in either the VCF math or the rounding digit count are
    caught. Using ``==`` against the exact baseline is safe here because
    ``compute_net_gallons`` rounds to one decimal — the result is always
    representable exactly in floating point for a 0.1-gallon granularity
    at this magnitude.

    Validates: Requirement 2.3
    """
    gross_gallons = 8_000.0
    temperature_f = 72.0  # ambient above 60 °F ⇒ expect net < gross
    api_gravity = 35.0    # #2 diesel

    net_gallons = _CALCULATOR.compute_net_gallons(
        gross_gallons=gross_gallons,
        temperature_f=temperature_f,
        api_gravity=api_gravity,
    )

    # Baseline captured from the polynomial implementation (Task 2.7 brief
    # explicitly states we should use the implementation as the reference,
    # not printed table values).
    assert net_gallons == pytest.approx(7975.3, abs=0.05)

    # Separately pin the rounding contract so a regression in the rounding
    # digit count (e.g. round(net, 2)) is caught even if the math drifts.
    assert net_gallons == round(net_gallons, 1)
    # And the absolute tolerance above is one rounding step — anything
    # larger would let through a truly wrong VCF.


def test_compute_net_gallons_is_less_than_gross_when_hot() -> None:
    """Sanity: hot fuel has expanded so the rounded net must be < gross.

    Validates: Requirement 2.3
    """
    gross_gallons = 8_000.0
    net_gallons = _CALCULATOR.compute_net_gallons(
        gross_gallons=gross_gallons,
        temperature_f=80.0,
        api_gravity=35.0,
    )
    assert net_gallons < gross_gallons


def test_compute_net_gallons_is_greater_than_gross_when_cold() -> None:
    """Sanity: cold fuel has contracted so the rounded net must be > gross.

    Validates: Requirement 2.3
    """
    gross_gallons = 8_000.0
    net_gallons = _CALCULATOR.compute_net_gallons(
        gross_gallons=gross_gallons,
        temperature_f=40.0,
        api_gravity=35.0,
    )
    assert net_gallons > gross_gallons


def test_compute_net_gallons_equals_gross_at_reference_temperature() -> None:
    """At 60 °F the VCF is exactly 1 ⇒ net == gross exactly.

    Validates: Requirements 2.2, 2.3
    """
    gross_gallons = 8_000.0
    net_gallons = _CALCULATOR.compute_net_gallons(
        gross_gallons=gross_gallons,
        temperature_f=REFERENCE_TEMPERATURE_F,
        api_gravity=35.0,
    )
    assert net_gallons == gross_gallons


