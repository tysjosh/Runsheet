    @staticmethod
    def _serialize_driver(driver: Driver) -> Dict[str, Any]:
        """Serialize a Driver model to an ES-compatible dict.

        Converts date/datetime fields to ISO format strings for ES
        indexing.
        """
        doc: Dict[str, Any] = {
            "driver_id": driver.driver_id,
            "tenant_id": driver.tenant_id,
            "full_name": driver.full_name,
            "cdl_number": driver.cdl_number,
            "cdl_state": driver.cdl_state,
            "cdl_class": driver.cdl_class,
            "cdl_expiry_date": driver.cdl_expiry_date.isoformat(),
            "medical_card_expiry_date": driver.medical_card_expiry_date.isoformat(),
            "hazmat_endorsement_expiry_date": (
                driver.hazmat_endorsement_expiry_date.isoformat()
                if driver.hazmat_endorsement_expiry_date
                else None
            ),
            "tanker_endorsement_expiry_date": (
                driver.tanker_endorsement_expiry_date.isoformat()
                if driver.tanker_endorsement_expiry_date
                else None
            ),
            "last_drug_test_date": (
                driver.last_drug_test_date.isoformat()
                if driver.last_drug_test_date
                else None
            ),
            "last_mvr_date": (
                driver.last_mvr_date.isoformat()
                if driver.last_mvr_date
                else None
            ),
            "status": driver.status,
            "suspension_reason": driver.suspension_reason,
            "external_refs": driver.external_refs,
            "created_at": driver.created_at.isoformat(),
            "updated_at": driver.updated_at.isoformat(),
        }
        return doc
