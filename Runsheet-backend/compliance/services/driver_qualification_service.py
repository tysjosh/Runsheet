"""Driver Qualification Service — DQF management and dispatch eligibility.

Implements the ``Driver_Qualification_Service`` described in design §5 of the
Fuel Compliance Backbone spec. This service manages driver qualification files
(CDL, medical card, HAZMAT endorsement, tanker endorsement, drug testing, MVR)
and provides:

* CRUD operations for Driver records in the ``drivers`` ES index.
* ``is_dispatch_eligible()`` — checks whether a driver meets route
  requirements (CDL class, endorsements, status). Implemented in Task 6.3.
* ``check_expiry_alerts()`` — daily cron scanning all drivers for upcoming
  qualification expirations at 60/30/7-day thresholds. Implemented in Task 6.4.
* ``get_dqf_dashboard()`` — tenant-wide compliance dashboard. Implemented
  in Task 6.7.
* ``check_drug_test_overdue()`` — flags drivers with overdue drug tests
  (Req 5.8). Implemented in Task 6.6.

All queries are tenant-scoped via ``inject_tenant_filter`` (Constraint C3).

Validates: Requirement 5.1
"""

