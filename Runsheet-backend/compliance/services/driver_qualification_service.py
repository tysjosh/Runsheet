# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

_DEFAULT_PAGE_LIMIT = 50
_MAX_PAGE_LIMIT = 200

# Alert thresholds in days (Req 5.2, 5.3, 5.4)
ALERT_THRESHOLD_WARNING_DAYS = 60
ALERT_THRESHOLD_URGENT_DAYS = 30
ALERT_THRESHOLD_CRITICAL_DAYS = 7

# Default drug test interval in days (typically annual per FMCSA)
DEFAULT_DRUG_TEST_INTERVAL_DAYS = 365


# ---------------------------------------------------------------------------
# Response models
# ---------------------------------------------------------------------------


class Alert(BaseModel):
    """Expiry alert generated by check_expiry_alerts."""

    model_config = ConfigDict(extra="forbid")

    driver_id: str
    tenant_id: str
    full_name: str
    qualification_type: str  # cdl | medical_card | hazmat | tanker
    expiry_date: date
    days_until_expiry: int
    severity: str  # warning | urgent | critical
    generated_at: datetime = Field(default_factory=utcnow)


class DriverEligibility(BaseModel):
    """Result of dispatch eligibility check."""

    model_config = ConfigDict(extra="forbid")

    driver_id: str
    eligible: bool
    reasons: List[str] = Field(default_factory=list)


class DQFDashboard(BaseModel):
    """Driver Qualification File compliance dashboard."""

    model_config = ConfigDict(extra="forbid")

    tenant_id: str
    total_drivers: int = 0
    active_drivers: int = 0
    suspended_drivers: int = 0
    expired_drivers: int = 0
    expiring_within_60_days: int = 0
    expiring_within_30_days: int = 0
    expiring_within_7_days: int = 0
    drug_test_overdue: int = 0
    generated_at: datetime = Field(default_factory=utcnow)


