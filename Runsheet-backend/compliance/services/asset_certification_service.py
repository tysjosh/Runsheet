    @staticmethod
    def _serialize_cert(cert: AssetCertification) -> Dict[str, Any]:
        """Serialize an AssetCertification model to an ES-compatible dict."""
        return {
            "cert_id": cert.cert_id,
            "tenant_id": cert.tenant_id,
            "asset_id": cert.asset_id,
            "certification_type": cert.certification_type,
            "certification_date": cert.certification_date.isoformat(),
            "expiry_date": cert.expiry_date.isoformat(),
            "inspector_name": cert.inspector_name,
            "certificate_number": cert.certificate_number,
            "status": cert.status,
            "created_at": cert.created_at.isoformat(),
            "updated_at": cert.updated_at.isoformat(),
        }

    @staticmethod
    def _parse_date(value: Any) -> Optional[date]:
        """Parse a date from an ISO string or return it if already a date."""
        if isinstance(value, date) and not isinstance(value, datetime):
            return value
        if isinstance(value, datetime):
            return value.date()
        if isinstance(value, str):
            try:
                return date.fromisoformat(value)
            except (ValueError, TypeError):
                return None
        return None
